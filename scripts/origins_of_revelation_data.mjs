#!/usr/bin/env node
/**
 * Data tooling for /discover/origins-of-revelation (src/data is read-only for the UI: these tools only
 * write page code and a proposal document for the data owner).
 *
 *   node scripts/origins_of_revelation_data.mjs --lock
 *       Writes src/utils/originsOfRevelation/dataLock.js from the current data (each quote position's
 *       reference + SHA-256 of its quote). Run it only after re-reading the card copy for every
 *       position the build reported as changed.
 *
 *   node scripts/origins_of_revelation_data.mjs --import-fixes <quote_fixes.json>
 *       Regenerates src/utils/originsOfRevelation/quoteFixes.js from verified quote fixes. Fails if a
 *       fix does not match the current data (stale), names a missing position, or changes nothing.
 *
 *   node scripts/origins_of_revelation_data.mjs --proposals <data_proposals.md>
 *       Writes the data proposals: every quote fix (file + JSON path + old/new text, byte-identical)
 *       and the Discover catalog card (content.js CATALOG), each with the SHA-256 of the proposed text.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import DATA from '../src/data/discover/islam/scripture/demonic_revelation.json' with { type: 'json' };
import CATALOG from '../src/data/discoverCatalog.json' with { type: 'json' };
import { DATA_FILE, CATALOG_FILE, CATALOG_SLUG, LAYOUT_TITLE_SUFFIX } from '../src/utils/originsOfRevelation/config.js';
import { resolveData, makeLock, sha256, dataPositions } from '../src/utils/originsOfRevelation/fixes.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const at = p => path.join(ROOT, p);
const arg = name => { const i = process.argv.indexOf(name); return i > -1 ? process.argv[i + 1] : null; };
const FIXES_JS = 'src/utils/originsOfRevelation/quoteFixes.js';
const LOCK_JS = 'src/utils/originsOfRevelation/dataLock.js';

/** JSON path of a data position, e.g. items[0].comparatives[0].islamic_quotes[2]. */
function jsonPath(f) {
  const i = DATA.items.findIndex(it => it.id === f.itemId);
  return `items[${i}].comparatives[0].${f.group}[${f.index}]`;
}

if (process.argv.includes('--lock')) {
  const lock = makeLock(DATA);
  const head = fs.readFileSync(at(LOCK_JS), 'utf8').split('export const DATA_LOCK')[0];
  fs.writeFileSync(at(LOCK_JS), `${head}export const DATA_LOCK = ${JSON.stringify(lock, null, 2)};\n`);
  console.log(`Wrote ${Object.keys(lock).length} locked positions to ${LOCK_JS} (data SHA-256 ${sha256(fs.readFileSync(at(DATA_FILE), 'utf8'))})`);
}

const importPath = arg('--import-fixes');
if (importPath) {
  const raw = JSON.parse(fs.readFileSync(importPath, 'utf8'));
  const list = Array.isArray(raw) ? raw : raw.fixes;
  if (!Array.isArray(list)) throw new Error('quote_fixes.json must be an array (or { fixes: [...] })');
  const fixes = list.map(f => ({
    itemId: f.itemId, group: f.group, index: f.index,
    oldReference: f.oldReference, newReference: f.newReference ?? f.oldReference,
    oldQuote: f.oldQuote, newQuote: f.newQuote ?? f.oldQuote,
    sourceFile: f.sourceFile ?? null, sourceKey: f.sourceKey ?? null, url: f.url ?? null,
    edits: f.verification?.declaredWordEdits ?? [],
    displayLabel: f.displayLabel ?? null,
    priority: f.priority ?? null, reason: f.reason ?? null, note: f.note ?? null,
  }));
  resolveData(DATA, fixes, null); // same checks as the build: stale, missing position, no-op, source mismatch
  const head = fs.readFileSync(at(FIXES_JS), 'utf8').split('export const QUOTE_FIXES')[0];
  fs.writeFileSync(at(FIXES_JS), `${head}export const QUOTE_FIXES = ${JSON.stringify(fixes, null, 2)};\n`);
  console.log(`Wrote ${fixes.length} fixes to ${FIXES_JS} (source SHA-256 ${sha256(fs.readFileSync(importPath, 'utf8'))})`);
}

const proposalsPath = arg('--proposals');
if (proposalsPath) {
  const { QUOTE_FIXES } = await import(at(FIXES_JS));
  const content = await import(at('src/utils/originsOfRevelation/content.js'));
  resolveData(DATA, QUOTE_FIXES, null);
  const { positions } = dataPositions(DATA);
  const out = [];
  out.push('# Data proposals: /discover/origins-of-revelation', '');
  out.push('Generated by `node scripts/origins_of_revelation_data.mjs --proposals`. `src/data/` is read-only for the UI; the page applies these at render time (`src/utils/originsOfRevelation/quoteFixes.js`). Once the data owner applies them, the build fails with "already applied in the data", the fix list is re-imported without them, and the data lock is refreshed (`--lock`).', '');
  out.push(`Data file: \`${DATA_FILE}\` (current SHA-256 \`${sha256(fs.readFileSync(at(DATA_FILE), 'utf8'))}\`, ${positions.size} quote positions)`, '');
  out.push('Every text block below is byte-identical to what the page renders from (quoted as JSON strings). The SHA-256 is of the proposed string (UTF-8, no JSON escaping).', '');
  QUOTE_FIXES.forEach((f, n) => {
    const base = jsonPath(f);
    out.push(`## ${n + 1}. ${f.itemId} · ${f.group}[${f.index}]${f.priority ? ` (${f.priority})` : ''}`, '');
    if (f.reason) out.push(`Why: ${f.reason}`, '');
    if (f.sourceFile) out.push(`Verified against: \`${f.sourceFile}\`${f.sourceKey ? ` → \`${f.sourceKey}\`` : ''}${f.url ? ` (${f.url})` : ''}`, '');
    if (f.displayLabel) out.push(`Display label (page only): ${f.displayLabel}`, '');
    if (f.edits?.length) out.push(`Declared word edits: ${f.edits.map(e => `\`${e}\``).join('; ')}`, '');
    if (f.newReference !== f.oldReference) {
      out.push(`- **\`${base}.reference\`**`, `  - old: \`${JSON.stringify(f.oldReference)}\``, `  - new: \`${JSON.stringify(f.newReference)}\``, `  - SHA-256(new): \`${sha256(f.newReference)}\``);
    }
    if (f.newQuote !== f.oldQuote) {
      out.push(`- **\`${base}.quote\`**`, '  - old:', '', '```json', JSON.stringify(f.oldQuote), '```', '', '  - new:', '', '```json', JSON.stringify(f.newQuote), '```', '', `  - SHA-256(new): \`${sha256(f.newQuote)}\``);
    }
    if (f.newReference === f.oldReference && f.newQuote === f.oldQuote) out.push('- No text change (display label only).');
    if (f.note) out.push('', `Note: ${f.note}`);
    out.push('');
  });
  const ci = CATALOG.findIndex(e => e.slug === CATALOG_SLUG);
  const proposed = content.CATALOG;
  if (ci > -1 && proposed) {
    out.push(`## Catalog card: \`${CATALOG_FILE}\` [${ci}] (slug \`${CATALOG_SLUG}\`, unchanged)`, '');
    for (const k of ['title', 'description']) {
      const v = String(proposed[k]).replace(new RegExp(`${LAYOUT_TITLE_SUFFIX.replace(/[|]/g, '\\|')}$`), '');
      if (v === CATALOG[ci][k]) { out.push(`- \`[${ci}].${k}\`: unchanged`); continue; }
      out.push(`- **\`[${ci}].${k}\`**`, `  - old: \`${JSON.stringify(CATALOG[ci][k])}\``, `  - new: \`${JSON.stringify(v)}\``, `  - SHA-256(new): \`${sha256(v)}\``);
    }
    out.push('');
  }
  fs.writeFileSync(proposalsPath, out.join('\n'));
  console.log(`Wrote ${proposalsPath}: ${QUOTE_FIXES.length} quote fixes${proposed ? ' + catalog card' : ''}`);
}

if (!process.argv.includes('--lock') && !importPath && !proposalsPath) {
  console.error('usage: --lock | --import-fixes <quote_fixes.json> | --proposals <data_proposals.md>');
  process.exit(2);
}
