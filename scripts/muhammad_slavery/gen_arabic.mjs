#!/usr/bin/env node
/**
 * Writes src/utils/muhammadSlavery/arabic.js: the Arabic of every key-quote hadith on the "Muhammad and
 * slavery" pages, from the fawazahmed0 mirror of Sunnah.com (`ara-<collection>`). Re-run whenever a key
 * quote changes (the build then shows the new Arabic; verify_muhammad_slavery_quotes.mjs re-checks it).
 *
 *   node --experimental-sqlite scripts/muhammad_slavery/gen_arabic.mjs [--cache <dir>] [--out <file>]
 *
 * Key quotes come from the model itself (`model.keyQuoteRefs`), so this script never drifts from the copy.
 * Texts added from outside the dataset (EXTRA_TEXTS) carry their own Arabic in extraTexts.js.
 */
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, arg, loadModel, mirrorIndex } from './lib.mjs';

process.chdir(ROOT);
const cache = arg('--cache') || undefined;
const out = path.resolve(ROOT, arg('--out') || 'src/utils/muhammadSlavery/arabic.js');
const { model } = loadModel();

const refs = [...model.keyQuoteRefs].sort();
const indexes = {};
const arabic = {};
const missing = [];
for (const ref of refs) {
  const [col, num] = ref.split(':');
  indexes[col] ||= await mirrorIndex(col, 'ara', { cache });
  const text = indexes[col].get(num);
  if (text) arabic[ref] = text.trim();
  else missing.push(ref);
}
if (missing.length) { console.error(`No mirror Arabic for: ${missing.join(', ')}`); process.exit(1); }

fs.writeFileSync(out, `/**
 * Arabic text for the key-quote hadith of each item, from the fawazahmed0 mirror of Sunnah.com
 * (\`ara-<collection>\`). Keyed by canonical ref ("bukhari:6707", "muslim:1456a"). Texts added from outside
 * the dataset carry their Arabic in extraTexts.js.
 *
 * GENERATED by scripts/muhammad_slavery/gen_arabic.mjs — do not hand-edit; re-run it when key quotes change.
 */
export const ARABIC = ${JSON.stringify(arabic, null, 2)};
`);
console.log(`arabic.js: ${Object.keys(arabic).length} key-quote texts written to ${path.relative(ROOT, out)}`);
