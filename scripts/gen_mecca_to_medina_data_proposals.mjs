#!/usr/bin/env node
/**
 * Data proposals for /discover/from-mecca-to-medina, generated from the override layer
 * (src/utils/meccaToMedina/config.js), so every proposed string is byte-identical to its override.
 *
 *   node scripts/gen_mecca_to_medina_data_proposals.mjs                 # print to stdout
 *   node scripts/gen_mecca_to_medina_data_proposals.mjs --out FILE      # write FILE
 *   node scripts/gen_mecca_to_medina_data_proposals.mjs --check FILE    # exit 1 (with a diff hint) if FILE is stale
 *
 * "override" strings are exactly what config.js holds (markdown and {placeholders} as written); where the
 * page fills or strips them, the rendered form is listed next to it as "rendered". The unit test
 * (model.test.mjs) proves every override string appears verbatim; `--check` proves a saved copy is current.
 * Once the data agent absorbs a block, delete the matching override in config.js and read the dataset.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as cfg from '../src/utils/meccaToMedina/config.js';
import { buildModel, resolvePath } from '../src/utils/meccaToMedina/model.js';
import { repoProviders } from '../src/utils/meccaToMedina/providers.js';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATASET = 'src/data/discover/islam/scripture/from_mecca_to_medina.json';
const CATALOG = 'src/data/discoverCatalog.json';

/** JSON literal in a code span: the exact override string, escapes and all. */
export const J = v => '`' + JSON.stringify(v) + '`';
const textOf = v => (v == null ? null : typeof v === 'string' ? v : Array.isArray(v) ? v : v.text ?? v);

/** Builds the proposals markdown. Reads src/data relative to `root` (providers use the working directory). */
export function generateProposals({ root = ROOT } = {}) {
  const prev = process.cwd();
  process.chdir(root);
  try {
    const data = JSON.parse(fs.readFileSync(DATASET, 'utf8'));
    const catalog = JSON.parse(fs.readFileSync(CATALOG, 'utf8'));
    const model = buildModel(data, cfg.CONFIG, repoProviders());
    return render({ data, catalog, model });
  } finally {
    process.chdir(prev);
  }
}

function render({ data, catalog, model }) {
  const out = [];
  const P = (...s) => out.push(...s);
  const before = paths => (paths || []).map(p => `  - before \`${p}\`: ${J(resolvePath(data, p))}`);
  const both = (override, rendered) => (override === rendered ? J(override) : `${J(override)} (rendered ${J(rendered)})`);

  P('# Data proposals: /discover/from-mecca-to-medina');
  P('');
  P('Generated by `scripts/gen_mecca_to_medina_data_proposals.mjs` from `src/utils/meccaToMedina/config.js`. Every proposed string is byte-identical to its override in config.js (markdown and `{placeholders}` as written); where the page fills or strips it, the rendered form follows in parentheses. Once the data agent absorbs a block, delete the matching override in config.js and read the field from the dataset.');
  P('');
  P('Files: `src/data/discover/islam/scripture/from_mecca_to_medina.json` (= MM) and `src/data/discoverCatalog.json` (= CAT). Strings are JSON literals.');
  P('');
  P('## 1. Discover catalog card (CAT, `"slug": "from-mecca-to-medina"`) — needs user sign-off');
  const ci = catalog.findIndex(c => c.slug === 'from-mecca-to-medina');
  P(`- \`[${ci}].title\`: ${J(catalog[ci]?.title)} → ${J(cfg.CATALOG.title)}`);
  P(`- \`[${ci}].description\`: ${J(catalog[ci]?.description)} → ${J(cfg.CATALOG.description)}`);
  P('');
  P('## 2. SEO and page opening — needs user sign-off');
  P(`- SEO title: ${both(cfg.SEO.title, model.seo.title)}`);
  P(`- meta description: ${both(cfg.SEO.description, model.seo.description)}`);
  P(`- keywords: ${J(cfg.SEO.keywords)}`);
  P(`- FAQPage JSON-LD: OFF (\`EMIT_FAQ = false\`); the old page's 7 Q/As are retired (4 were found wrong or misattributed in factcheck.md). Pending user decision.`);
  P(`- H1 → ${both(cfg.INTRO.h1, model.intro.h1)}`);
  P(`- \`meta.title\`: ${J(data.meta.title)} → ${both(cfg.SEO.title, model.seo.title)}; \`meta.subtitle\`: ${J(data.meta.subtitle)} → remove (verdict wording)`);
  P(`- MM \`abstract.summary\` → ${J(cfg.INTRO.text)} (rendered with {items} = ${model.counts.items})`);
  P(...before(cfg.INTRO.own));
  P(`- orientation line → ${J(cfg.INTRO.orientation)}`);
  P('');
  P('## 3. Reader-question sections');
  P('Proposal: a top-level `sections` array (or `question` / `dek` per section) carrying these strings; the page groups items into these questions.');
  for (const s of cfg.SECTIONS) {
    P(`- \`${s.id}\`: question ${J(s.question)}; dek ${J(textOf(s.dek))}; items ${J(s.items)}`);
    P(...before(s.own));
  }
  P('');
  P('## 4. Items (editorial fields)');
  P('Proposal: an `editorial` object `{ id, title, hook, takeaway, classical, comparison }` per item (keyed by the stable id), replacing the dataset prose it absorbs (shown as "before"). Showcase specs, excerpts and labels stay presentation config.');
  for (const [id, it] of Object.entries(cfg.ITEMS)) {
    const m = model.items.find(x => x.id === id);
    P('');
    P(`### \`${id}\` (item ${m?.number})`);
    P(`- after: ${J({ id, title: textOf(it.title), hook: it.hook, takeaway: it.takeaway, classical: textOf(it.classical) ?? null, comparison: textOf(it.comparison) ?? null })}`);
    if (m && m.title !== textOf(it.title)) P(`  - rendered title: ${J(m.title)}`);
    P(...before(it.own));
    for (const c of it.collapsed || []) {
      P(`- collapsed part ${J(c.heading)}${c.badge ? ` [${c.badge}]` : ''}: ${J(c.body ?? null)}`);
      P(...before(c.own));
    }
  }
  P('');
  P('## 5. Closing');
  const R = cfg.CLOSING;
  P(`- \`${R.readToday.id}\` title ${J(R.readToday.title)}; cards ${J(R.readToday.cards)}; outro ${J(R.readToday.outro)}`);
  P(...before(R.readToday.own));
  P('  - note: the old "Historical-Critical" sentence ("…an autocratic military commander … eliminate opposition") is retired: factcheck found no scholar who holds it, so it cannot be attributed (playbook §2.2).');
  P(`- \`${R.textsShow.id}\` title ${J(R.textsShow.title)}; intro ${J(R.textsShow.intro)}; rows = the ${model.counts.items} item takeaways (§4)`);
  P(...before(R.textsShow.own));
  P(`- \`${R.reflection.id}\` disclosure ${J(R.reflection.disclosure)}; title ${J(R.reflection.title)}; headers ${J(R.reflection.headers)}; rows ${J(R.reflection.rows)}; note ${J(R.reflection.note)}`);
  P(...before(R.reflection.own));
  P('');
  P('## 6. Quote-integrity and link fixes (dataset fields)');
  P('Shown on the page through `QUOTE_FIXES` until the dataset is corrected. "after" is the field value the page reads.');
  for (const f of model.quoteFixLog) {
    P(`- \`${f.ref}.${f.field}\`: ${J(f.before)} → ${J(f.after)}`);
    P(`  - reason: ${f.reason} (${f.sourceUrl})`);
  }
  P('');
  P('## 7. New sources (not in the dataset yet)');
  P('### 7a. Hadith (verbatim English of the fawazahmed0/hadith-api mirror of Sunnah.com)');
  for (const [key, x] of Object.entries(cfg.EXTRA_HADITH)) {
    P(`- \`${key}\` ${x.url} (${x.reference}); mirror ${x.mirror}`);
    P(`  - reason: ${x.reason}`);
    P(`  - text: ${J(x.text)}`);
  }
  const collect = (v, acc = new Set()) => {
    if (Array.isArray(v)) v.forEach(x => collect(x, acc));
    else if (v && typeof v === 'object') Object.values(v).forEach(x => collect(x, acc));
    else if (typeof v === 'string' && /^(quran|tafsir):/.test(v)) acc.add(v);
    return acc;
  };
  const refs = [...collect(cfg.ITEMS), ...collect(cfg.CLOSING)];
  P("### 7b. Qurʾān verses and tafsīr passages (from the repo's own Qurʾān / tafsīr JSON)");
  for (const r of [...new Set(refs)].sort()) P(`- \`${r}\``);
  const dataUrls = new Set(JSON.stringify(data).match(/https:\/\/sunnah\.com\/[a-z]+:[\w.]+/g));
  const extraUrls = new Set(Object.values(cfg.EXTRA_HADITH).map(x => x.url));
  const fixedUrls = new Set(model.quoteFixLog.filter(f => f.field === 'url').map(f => f.after));
  const linkOnly = (model.sourceGroups.find(g => g.kind === 'sunnah')?.items || []).filter(s => !dataUrls.has(s.href) && !extraUrls.has(s.href) && !fixedUrls.has(s.href));
  P('### 7c. Sunnah.com pages linked from our copy only');
  for (const s of linkOnly) P(`- ${s.label}: ${s.href}`);
  P('### 7d. Classical works linked from our copy (IslamWeb / Shamela / Wikisource)');
  for (const s of model.sourceGroups.find(g => g.kind === 'classical')?.items || []) P(`- ${s.label}: ${s.href}`);
  P('');
  P('## 8. Dataset print references whose page numbers were not checked');
  P('Claimed in config `own` and not shown on the page; the page lists these works by name only (PRINT_SOURCES). Verify the edition and page, or drop the page numbers.');
  {
    const seen = new Set();
    const walk = (x, p) => {
      if (Array.isArray(x)) {
        if (/\.(sources|historicalSources)$/.test(p)) x.forEach((t, i) => { if (typeof t === 'string' && !/Guillaume/.test(t) && !seen.has(`${p}[${i}]`)) { seen.add(`${p}[${i}]`); P(`- \`${p}[${i}]\`: ${J(t)}`); } });
        else x.forEach((v, i) => walk(v, `${p}[${i}]`));
      } else if (x && typeof x === 'object') for (const [k, v] of Object.entries(x)) walk(v, p ? `${p}.${k}` : k);
    };
    walk(data, '');
  }
  P('');
  P('## 9. Repo hadith corpus fixes (src/data/hadith; the page hides the Arabic until fixed)');
  for (const [key, h] of Object.entries(cfg.HIDE_HADITH_ARABIC || {})) {
    P(`- \`${key}\` (${h.corpus}): corrupt Arabic ${J(h.corrupt)}`);
    P(`  - reason: ${h.reason}`);
  }
  P('');
  P(`Counts: ${model.counts.items} items · ${model.counts.sunnahRefs} Sunnah.com pages · ${model.counts.quranRefs} Qurʾān passages · ${model.counts.tafsirRefs} tafsīr pages · ${model.counts.evidence} evidence cards.`);
  return out.join('\n') + '\n';
}

/** Every override string the proposals promise, for the unit test's byte-identity check. */
export function overrideStrings() {
  const list = [cfg.CATALOG.title, cfg.CATALOG.description, cfg.SEO.title, cfg.SEO.description, cfg.SEO.keywords, cfg.INTRO.h1, cfg.INTRO.text];
  for (const s of cfg.SECTIONS) list.push(s.question, textOf(s.dek));
  for (const it of Object.values(cfg.ITEMS)) {
    list.push(textOf(it.title), it.hook, it.takeaway);
    for (const c of it.collapsed || []) list.push(c.heading, c.body ?? null);
  }
  const R = cfg.CLOSING;
  list.push(R.readToday.title, R.readToday.outro, R.textsShow.title, R.textsShow.intro, R.reflection.disclosure, R.reflection.title, R.reflection.note);
  for (const x of Object.values(cfg.EXTRA_HADITH)) list.push(x.text);
  return list.filter(v => typeof v === 'string');
}

// ---- CLI ------------------------------------------------------------------------------------------
if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const arg = name => { const i = process.argv.indexOf(name); return i > -1 ? process.argv[i + 1] : null; };
  const text = generateProposals();
  const check = arg('--check');
  const outFile = arg('--out');
  if (check) {
    const saved = fs.existsSync(check) ? fs.readFileSync(check, 'utf8') : null;
    if (saved === text) { console.log(`${check} is current (byte-identical to config.js)`); process.exit(0); }
    const a = (saved ?? '').split('\n'), b = text.split('\n');
    const line = a.findIndex((l, i) => l !== b[i]);
    console.error(`${check} is stale${saved == null ? ' (missing)' : ` from line ${line + 1}`}:\n  saved:     ${String(a[line] ?? '').slice(0, 160)}\n  generated: ${String(b[line] ?? '').slice(0, 160)}\nRegenerate: node scripts/gen_mecca_to_medina_data_proposals.mjs --out ${check}`);
    process.exit(1);
  }
  if (outFile) { fs.writeFileSync(outFile, text); console.log(`wrote ${outFile}`); }
  else process.stdout.write(text);
}
